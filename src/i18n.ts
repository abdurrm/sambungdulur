export type Key = keyof typeof en;



// English is built in (the fallback and the source of the keys); the other languages load on demand.
const DICTS: Partial<Record<Lang, Record<Key, string>>> = { en };

/** Fetches a language's strings once; call before `setLang`. */
export async function loadLang(l: Lang): Promise<void> {
  if (DICTS[l]) return;
  DICTS[l] = (await (l === 'id' ? import('./lang/id') : import('./lang/jv'))).default;
}

